"""Patient-friendly audit report as PDF in the patient's language (shareable with family, hospital desk or insurer)."""
from __future__ import annotations
from datetime import date
from html import escape
from core.fmt import money
from core.pdfhtml import html_to_pdf
from core.schemas import ClaimReport

MODE = {"pre_discharge": "Pre-discharge check", "pre_submission": "Pre-submission check", "appeal": "Appeal review"}
STATUS = {"fixable": "Fix now", "contestable": "Contest", "needs_review": "Check", "valid": "Valid cut"}
DEFAULT_LABELS = {"title": "ClaimShield — claim audit report", "claimed": "Claimed", "now": "Insurer pays now", "after": "After the fixes",
                  "paid": "Insurer paid", "correct": "Correct payout", "risk": "Claim risk", "todo": "What to do", "findings": "Findings",
                  "what_do": "What to do", "collect": "Documents to collect", "who": "Who", "when": "When", "impact": "Impact",
                  "footer": "Amounts are computed deterministically from your policy wording and bill. Decision support, not legal advice. "
                            "Generated by ClaimShield (open source) using Meta Muse Spark."}


def report_pdf(rep: ClaimReport, policy_name: str, hospital: str | None, style: str = "indian", lang: str | None = None,
               labels: dict | None = None) -> bytes:
    L = lang or rep.user_lang or "en"
    lab = {**DEFAULT_LABELS, **(labels or {})}
    M = lambda x: escape(money(x, "₹", style))
    E = lambda s: escape(str(s or ""))
    appeal = rep.mode == "appeal"
    h = [f"<h1>{E(lab['title'])}</h1>",
         f"<p class='muted'>{E(MODE.get(rep.mode, rep.mode))} · {date.today():%d %b %Y} · {E(policy_name)}" + (f" · {E(hospital)}" if hospital else "") + "</p>",
         "<table><tr>" + "".join(f"<th>{E(x)}</th>" for x in (lab["claimed"], lab["paid"] if appeal else lab["now"], lab["correct"] if appeal else lab["after"], lab["risk"])) + "</tr><tr>"
         + f"<td class='num'>{M(rep.claimed)}</td><td class='num'>{M(rep.payout_before)}</td>"
         + f"<td class='num'>{M(rep.payout_after_appeal if appeal else rep.payout_after_fixes)}</td><td class='num'>{rep.risk_score}/100</td></tr></table>",
         f"<div class='box'>{E(rep.summary_localized if L != 'en' and rep.summary_localized else rep.summary_en)}</div>"]
    by = {f.id: f for f in rep.findings}
    if rep.action_plan:
        h.append(f"<h2>{E(lab['todo'])}</h2><table><tr><th>#</th><th>{E(lab['what_do'])}</th><th>{E(lab['who'])}</th><th>{E(lab['when'])}</th><th>{E(lab['impact'])}</th></tr>")
        for a in rep.action_plan:
            f = by.get(a["finding"])
            txt = a.get("action_localized", {}).get(L) or (f.fix_localized.get(L) if f else None) or a["action"]
            h.append(f"<tr><td>{a['step']}</td><td>{E(txt)}</td><td>{E(a['who'])}</td><td>{E(a['when'])}</td><td>{M(a['impact']) if a['impact'] else '—'}</td></tr>")
        h.append("</table>")
    h.append(f"<h2>{E(lab['findings'])}</h2>")
    for n, f in enumerate(rep.findings, 1):
        title = f.tool_evidence.get("title_localized", {}).get(L, f.title)
        h.append(f"<h3>{n}. {E(title)} — <span class='tag'>{E(STATUS.get(f.status, f.status))}</span> · {M(f.inr_impact)}</h3>")
        h.append(f"<p>{E(f.explanations.get(L) or f.explanation_en)}</p>")
        if f.fix:
            h.append(f"<p><b>{E(lab['what_do'])}:</b> {E(f.fix_localized.get(L) or f.fix)}</p>")
        if f.policy_cite and f.policy_cite.quote:
            h.append(f"<p class='quote'>Policy p.{f.policy_cite.page}: “{E(f.policy_cite.quote[:300])}”</p>")
        if f.irdai_cite:
            h.append(f"<p class='quote'>{E(f.irdai_cite.doc)}: {E(f.irdai_cite.quote[:300])}</p>")
    if rep.missing_docs:
        h.append(f"<h2>{E(lab['collect'])}</h2><ul>" + "".join(f"<li>{E(m['label'])}{' (critical)' if m['critical'] else ''}</li>" for m in rep.missing_docs) + "</ul>")
    h.append(f"<p class='muted'>{E(lab['footer'])}</p>")
    return html_to_pdf("".join(h))


def text_pdf(title: str, text: str, note: str = "") -> bytes:
    """Any text (e.g. a translated letter) as a PDF that renders every script."""
    paras = "".join(f"<p>{escape(p).replace(chr(10), '<br/>')}</p>" for p in text.split("\n\n") if p.strip())
    return html_to_pdf(f"<h1>{escape(title)}</h1>{paras}" + (f"<p class='muted'>{escape(note)}</p>" if note else ""))
